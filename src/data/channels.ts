export interface ShippingModeDef {
  id: ShippingMode;
  name: string;
  /** Kosten pro Lagereinheit Volumen (EUR). */
  costPerVolume: number;
  fixedCost: number;
  /** Laufzeit innerhalb derselben Region. */
  domesticDays: number;
  /** Laufzeit zwischen Regionen (null = nicht möglich). */
  intercontinentalDays: number | null;
  delayRisk: number;
  /** Aufschlag auf den Herstellerpreis (Großhandel). */
  pricePremium: number;
  /** Maximale Menge pro Bestellung (null = unbegrenzt). */
  maxQuantity: number | null;
  /** Fertigungsvorlauf des Herstellers fällt an (entfällt bei Lagerware). */
  usesSupplierLeadTime: boolean;
  description: string;
}

