function slot(
  key: SlotKey,
  type: ComponentType,
  label: string,
  formFactors: FormFactor[],
  options: Partial<Pick<CategorySlot, 'required' | 'quantity' | 'minor'>> = {},
): CategorySlot {
  return { key, type, label, formFactors, required: options.required ?? true, quantity: options.quantity ?? 1, minor: options.minor };
}

